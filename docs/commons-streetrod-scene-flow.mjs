function root(){return $('streetrod-summer');}
function arcade(){return body.classList.contains('arcade-on')&&body.dataset.arcadeGame==='streetrod';}
function room(){return body.dataset.arcadeScene||'garage';}
function source(){return $('ss-scene');}
function actionButton(label,roomName,disabled=false){
 const b=document.createElement('button');b.type='button';b.dataset.srRoom=roomName;
 b.textContent=label;b.disabled=disabled;return b;
}
function counter(){
 const info=$('ss-metrics')?.textContent||'';
 const garage=$('ss-scene')?.querySelector('.ss-garage-overlay span')?.textContent||'';
 const credits=info.match(/(?:bankroll|credits|cash)\s*:?\s*\$?[\d,]+/i)?.[0]||'';
 const car=garage||$('ss-scene')?.querySelector('.ss-scene-head h4')?.textContent||'';
 return {credits,car};
}
function navigate(next){
 if(!ROOM_IDS.has(next))return;
 // Use the actual saved season navigation, rather than synthesizing the
 // next screen. The existing arcade controller syncs to this pressed tab.
 const selected=$('ss-tabs')?.querySelector('[data-ss-tab="'+(next==='tune'?'garage':next)+'"]');
 if(selected&&!selected.disabled){selected.click();}
 if(next==='tune'){body.dataset.arcadeScene='tune';render(true);}
}
function activeCards(){
 const scene=source();if(!scene)return [];
 const roomId=room();
 if(roomId==='paper')return [...scene.querySelectorAll('.ss-ads >.ss-ad')];
 if(roomId==='diner')return [...scene.querySelectorAll('.ss-rivals >.ss-rival')];
 if(roomId==='parts')return [...scene.querySelectorAll('.ss-parts-counter > article')];
 return [];
}
function cloneRecord(record){
 const copy=record.cloneNode(true);
 copy.classList.remove('ss-ad','ss-rival');
 copy.classList.add('ss-dos-record');
 copy.querySelectorAll('[id]').forEach(el=>el.removeAttribute('id'));
 // Source content is already generated by the real game renderer. Cloned
 // action buttons/forms still bubble to its existing RPC dispatch handlers.
 return copy;
}
function stripActions(scene,keys,host,limit=6){
 let count=0;
 for(const b of scene.querySelectorAll('button[data-ss-action]')){
  if(count>=limit)break;
  if(!keys.has(b.dataset.ssAction)||b.disabled)continue;
  const copy=b.cloneNode(true);copy.classList.add('ss-dos-quick-action');
  copy.removeAttribute('id');host.append(copy);count++;
 }
 return count;
}
function footer(){
 const bar=document.createElement('div');bar.className='ss-dos-room-nav';
 for(const [label,target] of rooms[room()]||rooms.garage){
  bar.append(actionButton(label,target));
 }
 return bar;
}
function frame(roomId){
 const stage=document.createElement('section');stage.id='ss-dos-stage';stage.className='ss-dos-stage';
 stage.setAttribute('aria-label','Street r0d interactive '+roomId+' scene');
 const cover=document.createElement('div');cover.className='ss-dos-cover';
 const canvas=document.createElement('canvas');canvas.id='ss-dos-canvas';canvas.width=320;canvas.height=200;
 canvas.setAttribute('role','img');canvas.setAttribute('aria-label',roomId+' sixteen-colour DOS-style scene');
 const overlay=document.createElement('div');overlay.className='ss-dos-hotspots';
 for(const h of zones[roomId]||[]){
  const b=actionButton('',h.room);
  b.className='ss-dos-hotspot';b.title=h.name;b.setAttribute('aria-label',h.name);
  b.style.left=h.left+'%';b.style.top=h.top+'%';b.style.width=h.width+'%';b.style.height=h.height+'%';
  overlay.append(b);
 }
 cover.append(canvas,overlay);
 const info=document.createElement('p');info.id='ss-dos-hint';info.className='ss-dos-hint';
 info.setAttribute('role','status');info.textContent='Point at an object or choose a location below.';
 const pocket=document.createElement('div');pocket.id='ss-dos-pocket';pocket.className='ss-dos-pocket';
 pocket.setAttribute('aria-label','Current '+roomId+' action');
 stage.append(cover,info,pocket,footer());
 stage.addEventListener('pointerover',event=>{
  const h=event.target.closest('[data-sr-room]');if(h)info.textContent=h.title||h.textContent?.trim()||'SELECT';
 });
 stage.addEventListener('focusin',event=>{
  const h=event.target.closest('[data-sr-room]');if(h)info.textContent=h.getAttribute('aria-label')||h.textContent?.trim()||'SELECT';
 });
 stage.addEventListener('click',event=>{
  const target=event.target.closest('[data-sr-room]');if(!target||target.disabled)return;
  const next=target.dataset.srRoom;
  if(next==='prev'||next==='next'){move(next==='next'?1:-1);return;}
  if(next==='hood'){
   // The physical car workbench intercepts this original game action and
   // uses server revision numbers for each bolt turn. Never fake upgrades.
   const trigger=source()?.querySelector('[data-ss-action="workshop"]')||
    source()?.querySelector('[data-ss-action="service_advance"]');
   if(trigger)trigger.click();else navigate('parts');
   return;
  }
  if(next==='timing'||next==='tune'){
   navigate('garage');body.dataset.arcadeScene='tune';render(true);return;
  }
  navigate(next);
 });
 return stage;
}
function move(dir){
 const cards=activeCards();
 if(!cards.length)return;
 page=(page+dir+cards.length)%cards.length;
 displayRecord();
}
function displayRecord(){
 const host=$('ss-dos-pocket');if(!host)return;
 const now=room(),cards=activeCards();
 const openChallenge=host.querySelector('.ss-challenge-form');
 host.replaceChildren();
 const stage=$('ss-dos-stage');if(!stage)return;
 if(cards.length){
  page=Math.min(Math.max(page,0),cards.length-1);
  const row=document.createElement('div');row.className='ss-dos-record-head';
  const counter=document.createElement('span');counter.textContent=(now==='paper'?'CLASSIFIED':now==='diner'?'RIVAL':'PART')+' '+(page+1)+' / '+cards.length;
  const previous=actionButton('‹','prev'),next=actionButton('›','next');
  previous.setAttribute('aria-label','Previous '+now+' entry');
  next.setAttribute('aria-label','Next '+now+' entry');
  row.append(previous,counter,next);host.append(row,cloneRecord(cards[page]));
 }else if(now==='garage'){
  const quick=document.createElement('div');quick.className='ss-dos-short-actions';
  stripActions(source(),new Set(['refuel','repair','bumpers','roof']),quick,4);
  if(quick.childElementCount)host.append(quick);
 }else if(now==='tune'){
  const dial=source()?.querySelector('.ss-timing-bench')?.cloneNode(true);
  const form=source()?.querySelector('form[data-ss-form="tune"]')?.cloneNode(true);
  if(dial){dial.classList.add('ss-dos-timing');host.append(dial);}
  if(form){form.classList.add('ss-dos-tune-form');host.append(form);}
 }else if(now==='parts'){
  const inv=source()?.querySelector('.ss-inventory-item');
  if(inv)host.append(cloneRecord(inv));
 }else if(now==='drive'){
  const actual=source()?.querySelector('.ss-drive-controls,.ss-drive-panel,.ss-race-controls');
  if(actual)host.append(actual.cloneNode(true));
 }
 // Keep the original signed-in race challenge element and its listeners.
 const form=source()?.querySelector(':scope > .ss-challenge-form');
 if(form)host.append(form);
 else if(openChallenge)host.append(openChallenge);
}
function sceneData(){
 const c=counter(),key=c.car||'rattler',lower=key.toLowerCase();
 const bodyType=/van|bus/.test(lower)?'van':/truck|pickup/.test(lower)?'truck':
  /wagon|nomad/.test(lower)?'wagon':/muscle|fastback/.test(lower)?'muscle':
  /sedan|hardtop/.test(lower)?'hardtop':'coupe';
 const creditNumber=Number(c.credits.replace(/[^\d]/g,''))||undefined;
 return {carKey:key,body:bodyType,bankroll:creditNumber,label:c.car||'THE GARAGE'};
}
function paint(){
 const canvas=$('ss-dos-canvas');
 if(!canvas)return;
 window.COWBOY_STREETROD_PAINT?.(canvas,room(),sceneData());
}
function render(force=false){
 const scene=source();if(!arcade()||!scene||!root()||root().hidden||!ROOM_IDS.has(room())){
  $('ss-dos-stage')?.remove();return;
 }
 if(lastRoom!==room()){page=0;lastRoom=room();}
 let stage=$('ss-dos-stage');
 if(!stage||stage.parentElement!==scene||force){
  stage?.remove();stage=frame(room());scene.append(stage);
 }
 paint();displayRecord();
}
// Genuine two-turn mechanical bolts remain server-backed. The viewport only
// paginates the part diagrams so a mechanic never has to scroll the full page.
let partPage=0,bayObserver=null;
function syncWorkbench(){
 const bench=$('ss-season-bay'),list=bench?.querySelector('.ssb-components');
 if(!bench||!list)return;
 const cards=[...list.children].filter(el=>el.classList.contains('ssb-component'));
 if(!cards.length)return;
 partPage=Math.max(0,Math.min(cards.length-1,partPage));
 let nav=bench.querySelector('.ssb-pager');
 if(!nav){
  nav=document.createElement('nav');nav.className='ssb-pager';
  nav.setAttribute('aria-label','Physical engine and transmission parts');
  nav.innerHTML='<button type="button" data-ssb-page="-1" aria-label="Previous engine part">‹</button><strong class="ssb-pager-label"></strong><button type="button" data-ssb-page="1" aria-label="Next engine part">›</button>';
  list.before(nav);
 }
 cards.forEach((card,i)=>{card.hidden=i!==partPage;});
 const label=cards[partPage].querySelector('header strong')?.textContent?.trim()||'Component';
 const desc=label+' '+(partPage+1)+' / '+cards.length;
 if(nav.querySelector('.ssb-pager-label').textContent!==desc)nav.querySelector('.ssb-pager-label').textContent=desc;
 const older=nav.querySelector('[data-ssb-page="-1"]'),newer=nav.querySelector('[data-ssb-page="1"]');
 older.disabled=partPage===0;newer.disabled=partPage===cards.length-1;
}
function installBay(){
 const bench=$('ss-season-bay');
 if(!bench||bayObserver)return;
 bench.addEventListener('click',e=>{
  const b=e.target.closest('[data-ssb-page]');if(!b)return;
  e.preventDefault();partPage+=Number(b.dataset.ssbPage);syncWorkbench();
 });
 let pending=false;
 bayObserver=new MutationObserver(mutations=>{
  if(!mutations.some(m=>m.target.closest?.('.ssb-body')||m.target.classList?.contains('ssb-body')))return;
  if(pending)return;pending=true;requestAnimationFrame(()=>{pending=false;syncWorkbench();});
 });
 bayObserver.observe(bench,{subtree:true,childList:true});
 syncWorkbench();
}
let queued=false;
function schedule(){
 if(queued)return;queued=true;
 requestAnimationFrame(()=>{queued=false;render();installBay();});
}
function install(){
 const scene=source();if(!scene||installed)return false;
 installed=true;observer=new MutationObserver(mutations=>{
  // Ignore mutations within the facade itself to avoid a feedback loop.
  if(mutations.some(m=>m.target===scene||m.target.closest?.('#ss-scene')&&!m.target.closest?.('#ss-dos-stage')))schedule();
 });
 observer.observe(scene,{childList:true});
 const bodyObs=new MutationObserver(schedule);
 bodyObs.observe(body,{attributes:true,attributeFilter:['class','data-arcade-game','data-arcade-scene']});
 const rootObs=new MutationObserver(schedule);rootObs.observe(root(),{attributes:true,attributeFilter:['hidden']});
 schedule();return true;
}
if(!install()){
 installTimer=setInterval(()=>{if(install())clearInterval(installTimer);},500);
}
