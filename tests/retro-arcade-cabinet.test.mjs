import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {retroCabinetDirection,retroCabinetButton} from '../docs/retro-arcade-cabinet.mjs';
import {createRetroInput} from '../docs/retro-arcade-input.mjs';
import {initialRetro,retroStep,retroReplay,RETRO_GAME_RULES} from '../docs/retro-arcade-engine.mjs';
const source=name=>readFileSync(new URL('../docs/'+name,import.meta.url),'utf8');

test('only Mystery Maze and Star Squadron have two-way/four-way cabinet steering',()=>{
 assert.equal(retroCabinetDirection('maze',18,2),'R');
 assert.equal(retroCabinetDirection('maze',-18,2),'L');
 assert.equal(retroCabinetDirection('maze',2,-18),'U');
 assert.equal(retroCabinetDirection('maze',2,18),'D');
 assert.equal(retroCabinetDirection('maze',1,1),'N');
 assert.equal(retroCabinetDirection('fleet',18,90),'R','vertical swipe cannot change shooter ship lanes');
 assert.equal(retroCabinetDirection('fleet',-20,-90),'L');
 assert.equal(retroCabinetDirection('fleet',0,90),'N');
 assert.equal(retroCabinetDirection('mahjong',25,20),'N');
 assert.equal(retroCabinetDirection('maze',NaN,6),'N');
});
test('A action is legal and B pause never injects a server move',()=>{
 assert.equal(retroCabinetButton('fleet','A'),'F');
 assert.equal(retroCabinetButton('maze','A'),'B');
 assert.equal(retroCabinetButton('fleet','B'),null);
 assert.equal(retroCabinetButton('maze','B'),null);
 const fleet=createRetroInput();
 fleet.press('fleet','L');fleet.press('fleet',retroCabinetButton('fleet','A'));
 assert.equal(fleet.action('fleet'),'A');
 assert.equal(fleet.action('fleet'),'A','held A fires on every step');
 fleet.release('L');fleet.release('F');assert.equal(fleet.action('fleet'),'N');
 const maze=createRetroInput();
 let state=initialRetro('maze',3);
 maze.press('maze','R');let move=maze.action('maze',state);assert.equal(move,'R');
 state=retroStep(state,move);
 maze.press('maze',retroCabinetButton('maze','A'));
 assert.equal(maze.action('maze',state),'N');
 assert.equal(maze.action('maze',state),'N','holding A brakes without losing lives or score');
 maze.release('B');
 assert.equal(maze.action('maze',state),'R','releasing brake restores requested steering');
});
test('rapid brake tap is captured, server accepts neutral trace and replay matches',()=>{
 const pad=createRetroInput();
 let state=initialRetro('maze',6);
 pad.press('maze','R');const moves=[pad.action('maze',state)];state=retroStep(state,moves[0]);
 pad.press('maze','B');pad.release('B');
 moves.push(pad.action('maze',state));state=retroStep(state,moves.at(-1));
 assert.equal(moves.at(-1),'N');
 for(const ch of moves)assert.ok(RETRO_GAME_RULES.maze.controls.includes(ch));
 assert.deepEqual(state,retroReplay('maze',6,moves.join('')));
});
